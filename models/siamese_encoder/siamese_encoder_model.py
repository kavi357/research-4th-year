from torch.utils.data import Dataset, DataLoader

with open("music_features_colab.pkl", "rb") as f:
    raw = pickle.load(f)

features = {k: torch.tensor(v) for k,v in raw.items()}
track_ids = list(features.keys())

class TripletDataset(Dataset):
    def __len__(self):
        return len(track_ids) * 5

    def __getitem__(self, idx):
        a = random.choice(track_ids)
        n = random.choice([i for i in track_ids if i != a])

        anchor = features[a]
        positive = anchor + torch.randn_like(anchor) * 0.01
        negative = features[n]

        return anchor, positive, negative

dataset = TripletDataset()
loader = DataLoader(dataset, batch_size=32, shuffle=True)

model = MusicEncoder()
