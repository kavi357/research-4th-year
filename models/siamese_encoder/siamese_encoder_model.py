for epoch in range(30):
    total_loss = 0
    for a,p,n in loader:
        ea, ep, en = model(a), model(p), model(n)

        loss = torch.relu(
            torch.nn.functional.pairwise_distance(ea, ep) -
            torch.nn.functional.pairwise_distance(ea, en) + 1.0
        ).mean()

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

    print(f"Epoch {epoch+1}: {total_loss/len(loader):.4f}")

torch.save(model.state_dict(), "music_siamese_encoder.pth")

